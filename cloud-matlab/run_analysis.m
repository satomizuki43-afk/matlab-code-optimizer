% 在真实 MATLAB 中运行完整分析，并核查全部 28 组实验均被保留。
% 仓库源码保持原样；只在临时验证目录中使用与主函数同名的副本。

analysisRepoRoot = fileparts(fileparts(mfilename('fullpath')));
analysisSource = fullfile(analysisRepoRoot,'genggai1101.m');
analysisWorkDir = '/workspace/work/matlab-validation';
analysisOutputDir = fullfile(analysisWorkDir,'results');

assert(isfile(analysisSource),'找不到仓库源文件：%s',analysisSource);
if ~isfolder(analysisWorkDir)
    mkdir(analysisWorkDir);
end

analysisCopy = fullfile(analysisWorkDir,'fdm_paper_analysis.m');
[analysisCopied,analysisCopyMessage] = copyfile(analysisSource,analysisCopy,'f');
assert(analysisCopied,'无法创建验证副本：%s',analysisCopyMessage);

analysisPreviousPath = path;
analysisPathCleanup = onCleanup(@()path(analysisPreviousPath));
addpath(analysisWorkDir,'-begin');
clear fdm_paper_analysis;
rehash path;

analysisConfig = struct(...
    'ShowFigures',false,...
    'MakeFigures',true,...
    'OutDir',analysisOutputDir);
results = fdm_paper_analysis(analysisConfig);

assert(height(results.Data) == 28,'总数据必须包含 28 组。');
assert(isequal(sort(results.Data.GroupID(:)),(1:28)'),...
    '总数据组号必须恰好为 1 至 28。');
assert(all(results.Data.CF(results.Data.GroupID <= 14) == 10) && ...
    all(results.Data.CF(results.Data.GroupID >= 15) == 15),...
    '材料分界错误：第 15 组应为 15CF 的首组。');
assert(sum(results.Data.CF == 10) == 14 && ...
    sum(results.Data.CF == 15) == 14,...
    '两种材料必须各包含 14 组。');
assert(isempty(results.Config.LegacyExcludedIDs) && ...
    isempty(results.Config.CandidateExcludedIDs),...
    '不得配置任何排除组号。');
assert(all(results.Data.CandidateEligible),...
    '全部实测组必须具有评价资格。');
assert(numel(results.Material) == 2 && ...
    isequal(sort([results.Material.CF]),[10 15]),...
    '必须分别分析 10CF 和 15CF 两种材料。');

analysisResponseNames = sort(["FlexStrength";"FlexModulus";"FlexToughness"]);
for analysisMaterialIndex = 1:numel(results.Material)
    analysisMaterial = results.Material(analysisMaterialIndex);
    if analysisMaterial.CF == 10
        analysisExpectedIDs = (1:14)';
    else
        analysisExpectedIDs = (15:28)';
    end

    assert(height(analysisMaterial.Data) == 14 && ...
        height(analysisMaterial.Ranking) == 14 && ...
        height(analysisMaterial.WeightSensitivity) == 14,...
        'CF%g 的数据、排名及权重敏感性必须各保留 14 组。',analysisMaterial.CF);
    assert(isequal(sort(analysisMaterial.Data.GroupID(:)),analysisExpectedIDs) && ...
        isequal(sort(analysisMaterial.Ranking.GroupID(:)),analysisExpectedIDs) && ...
        isequal(sort(analysisMaterial.WeightSensitivity.GroupID(:)),analysisExpectedIDs),...
        'CF%g 的数据、排名及权重敏感性组号集合不一致。',analysisMaterial.CF);
    assert(all(analysisMaterial.Ranking.CandidateEligible),...
        'CF%g 的实测排名不得排除任何组。',analysisMaterial.CF);
    assert(height(analysisMaterial.Diagnostics) == 3 && ...
        all(analysisMaterial.Diagnostics.N == 14) && ...
        isequal(sort(string(analysisMaterial.Diagnostics.Response(:))),analysisResponseNames),...
        'CF%g 的三项响应诊断必须各使用 14 组。',analysisMaterial.CF);
end

assert(height(results.Diagnostics) == 6 && ...
    all(results.Diagnostics.N == 14) && ...
    all(strcmp(results.Diagnostics.Scenario,'All')),...
    '总诊断应仅包含两种材料的六项全数据响应。');
assert(height(results.Summary) == 2 && ...
    all(strcmp(results.Summary.Scenario,'All')) && ...
    all(results.Summary.N == 14) && ...
    isequal(sort(results.Summary.CF(:)),[10;15]),...
    '汇总应仅有 10CF 和 15CF 两行 All 情景，每行 N=14。');

fprintf('\n验证通过：全部 28 组均参与分析，10CF=14 组，15CF=14 组。\n');
fprintf('输出目录：%s\n',analysisOutputDir);
clear analysisPathCleanup;
